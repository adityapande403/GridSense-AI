from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ForecastHorizonEnum(str, Enum):
    HORIZON_1H = "1h"
    HORIZON_4H = "4h"
    HORIZON_8H = "8h"
    HORIZON_24H = "24h"


class ForecastDataPoint(BaseModel):
    """Predicted load state for a future time step."""
    horizon_hours: int = Field(..., description="Hours ahead: 1, 4, 8, or 24")
    horizon_label: str = Field(..., description="e.g. '1-Hour Ahead (FLISR / Real-Time Dispatch)'")
    timestamp: str = Field(..., description="Predicted target ISO timestamp")
    hour_of_day: int = Field(..., description="Target hour 0-23")
    
    # Quantile GBDT Active Power Forecasts (TR-FOR-01, TR-FOR-03)
    predicted_load_kw: float = Field(..., description="Median (P50) predicted load in kW")
    confidence_p10_kw: float = Field(..., description="Lower 10th percentile bound in kW")
    confidence_p90_kw: float = Field(..., description="Upper 90th percentile bound in kW")
    
    # Transformer Stress
    predicted_loading_pct: float = Field(..., description="Projected transformer loading %")
    status: str = Field("NORMAL", description="'NORMAL', 'ELEVATED', 'NEAR_OVERLOAD', or 'CRITICAL_OVERLOAD'")
    is_overload: bool = Field(False, description="True if projected loading > 100%")
    
    # Environmental & Operational Context Features (TR-FOR-04)
    ambient_temp_c: float = Field(..., description="Forecasted ambient temperature in °C")
    is_ag_shift_active: bool = Field(False, description="Telangana 7-hour agricultural free power shift flag")
    
    model_name: str = "LightGBM_GBDT_Quantile_v1"
    provenance: str = Field("predicted", description="Must be labeled 'predicted' per Principle A4-7")


class ModelBenchmarkMetric(BaseModel):
    """Comparative benchmarking metrics between GBDT and baseline models (TR-FOR-02)."""
    horizon_hours: int
    horizon_label: str
    
    # LightGBM GBDT Performance
    model_mae_kw: float = Field(..., description="Mean Absolute Error in kW")
    model_rmse_kw: float = Field(..., description="Root Mean Squared Error in kW")
    model_mape_pct: float = Field(..., description="Mean Absolute Percentage Error (%)")
    model_r2: float = Field(..., description="Coefficient of determination R^2")
    
    # Baseline Benchmarks
    persistence_mae_kw: float = Field(..., description="Naive Persistence MAE (y_hat = y_t)")
    persistence_mape_pct: float = Field(..., description="Naive Persistence MAPE (%)")
    improvement_over_persistence_pct: float = Field(..., description="% error reduction achieved by ML over persistence")


class DTRForecastReport(BaseModel):
    """Complete rolling multi-horizon ML load forecast report for a transformer."""
    dtr_id: str
    dtr_code: str
    dtr_name: str
    rated_kva: float
    rated_kw: float
    
    current_load_kw: float
    current_loading_pct: float
    current_timestamp: str
    
    forecasts: List[ForecastDataPoint]
    benchmarks: List[ModelBenchmarkMetric]
    feature_importances: Dict[str, float] = Field(
        ...,
        description="GBDT Feature importance scores (e.g. {'lag_1h': 0.32, 'ag_shift_flag': 0.25, ...})"
    )
    
    validation_method: str = "Chronological Walk-Forward Validation (No Data Leakage)"
    provenance: str = "predicted"
    provenance_disclaimer: str = (
        "Projected load values generated by LightGBM Gradient Boosted Decision Tree models. "
        "Explicitly labeled 'predicted' in accordance with Non-negotiable Principle A4-7."
    )


class OverloadEarlyWarningAlert(BaseModel):
    """Actionable early warning alert with 4h to 24h lead time (TR-FOR-05)."""
    alert_id: str
    dtr_code: str
    dtr_name: str
    feeder_code: str
    rated_kva: float
    
    lead_time_hours: int = Field(..., description="Advance warning lead time (1, 4, 8, or 24 hours)")
    projected_timestamp: str
    projected_peak_kw: float
    projected_loading_pct: float
    
    severity: str = Field(..., description="'WARNING' (85-100%) or 'CRITICAL' (>100%)")
    primary_driver: str = Field(
        ...,
        description="e.g. 'Telangana Agricultural Shift Pumping Surge + Diurnal Thermal Peak'"
    )
    recommended_mitigation: str = Field(
        ...,
        description="e.g. 'Initiate FLISR tie-switch reconfiguration to transfer 45 kW to Feeder B via SW-04'"
    )
    is_acknowledged: bool = False
    provenance: str = "predicted"


class FeederForecastAlertsSummary(BaseModel):
    """Feeder-wide forecast and predictive overload early warnings overview."""
    feeder_code: str
    feeder_name: str
    total_dtrs_monitored: int
    active_alerts_count: int
    critical_alerts_count: int
    warning_alerts_count: int
    alerts: List[OverloadEarlyWarningAlert]
    provenance: str = "predicted"
