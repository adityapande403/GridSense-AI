import logging
import uuid
from typing import List, Literal, Optional
from uuid import UUID

from backend.src.models.network import Bus, Connection, Line
from backend.src.models.topology import TopologyDiff, TopologyVersion
from pydantic import BaseModel, Field
from sqlalchemy.orm import Session

logger = logging.getLogger(__name__)


class CandidateConnection(BaseModel):
    """
    Proposed topological connection generated by spatial proximity analysis.
    Principle A4-4: Geographic proximity is NEVER proof of electrical connectivity.
    Principle A4-9: AI / geometric heuristics NEVER auto-modify authoritative topology.
    """

    candidate_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    from_element_id: UUID
    from_element_type: Literal["bus", "line"]
    from_code: str
    to_element_id: UUID
    to_element_type: Literal["bus", "line"]
    to_code: str
    distance_meters: float
    confidence_score: float  # Scale 0.0 - 1.0 based on distance decay
    provenance: Literal["estimated"] = "estimated"
    status: Literal["candidate_for_review", "approved", "rejected"] = "candidate_for_review"
    potential_risk: Optional[str] = None
    explanation: str


class SnappingRulesEngine:
    """
    Proposes candidate connections for open/disconnected terminals within spatial proximity threshold.
    Strictly advisory: produces review items, never silently alters authoritative electrical connectivity.
    """

    def __init__(self, default_ht_tolerance_m: float = 5.0, default_lt_tolerance_m: float = 10.0):
        self.default_ht_tolerance_m = default_ht_tolerance_m
        self.default_lt_tolerance_m = default_lt_tolerance_m

    def find_snapping_candidates(
        self,
        db_session: Session,
        feeder_id: Optional[UUID] = None,
        tolerance_meters: Optional[float] = None,
    ) -> List[CandidateConnection]:
        tol = tolerance_meters or self.default_ht_tolerance_m

        bus_q = db_session.query(Bus)
        line_q = db_session.query(Line)
        if feeder_id:
            bus_q = bus_q.filter_by(feeder_id=feeder_id)
            line_q = line_q.filter_by(feeder_id=feeder_id)

        buses = bus_q.all()
        lines = line_q.all()

        # Find existing connections
        existing_edges = set()
        for line_item in lines:
            existing_edges.add((line_item.from_bus_id, line_item.to_bus_id))
            existing_edges.add((line_item.to_bus_id, line_item.from_bus_id))

        # Filter buses that have coordinates
        buses_with_coords = [b for b in buses if b.geom is not None]

        candidates: List[CandidateConnection] = []

        # Check pairwise distances between buses not already connected
        n = len(buses_with_coords)
        for i in range(n):
            b1 = buses_with_coords[i]
            for j in range(i + 1, n):
                b2 = buses_with_coords[j]

                # If already connected by an operational line, skip
                if (b1.id, b2.id) in existing_edges:
                    continue

                # Approximate distance in meters (~111,139 m per degree lat/lon)
                dx = (b1.geom.x - b2.geom.x) * 111139.0
                dy = (b1.geom.y - b2.geom.y) * 111139.0
                dist_m = (dx**2 + dy**2) ** 0.5

                if dist_m <= tol:
                    conf = max(0.1, round(1.0 - (dist_m / tol) * 0.5, 3))
                    risk = None
                    if abs(b1.voltage_level_kv - b2.voltage_level_kv) > 0.1:
                        risk = f"Voltage mismatch: {b1.voltage_level_kv} kV vs {b2.voltage_level_kv} kV."

                    cand = CandidateConnection(
                        from_element_id=b1.id,
                        from_element_type="bus",
                        from_code=b1.code,
                        to_element_id=b2.id,
                        to_element_type="bus",
                        to_code=b2.code,
                        distance_meters=round(dist_m, 2),
                        confidence_score=conf,
                        status="candidate_for_review",
                        potential_risk=risk,
                        explanation=(
                            f"Bus '{b1.code}' and Bus '{b2.code}' are located {dist_m:.2f} m apart "
                            f"(within snapping threshold of {tol} m). Candidate connection proposed for engineer review."
                        ),
                    )
                    candidates.append(cand)

        return candidates

    def approve_and_apply_candidate(
        self,
        candidate: CandidateConnection,
        db_session: Session,
        approver_name: str,
        conductor_type: str = "ACSR_Weasel",
    ) -> Line:
        """
        Operator-approved application of a snapping candidate.
        Principle A6: Explicit human approval layer. Creates a line and Connection record.
        """
        from_bus = db_session.get(Bus, candidate.from_element_id)
        to_bus = db_session.get(Bus, candidate.to_element_id)

        if not from_bus or not to_bus:
            raise ValueError("Invalid bus references in candidate connection.")

        new_line_code = f"SNAPPED_LINE_{from_bus.code}_{to_bus.code}"
        line = Line(
            feeder_id=from_bus.feeder_id,
            from_bus_id=from_bus.id,
            to_bus_id=to_bus.id,
            code=new_line_code,
            conductor_type=conductor_type,
            length_km=max(0.005, round(candidate.distance_meters / 1000.0, 4)),
            r_ohm_per_km=0.9075,
            x_ohm_per_km=0.377,
            max_i_ka=0.134,
            is_operational=True,
            source=f"OperatorApproval:{approver_name}",
            provenance="estimated",
            confidence_score=candidate.confidence_score,
        )
        db_session.add(line)
        db_session.flush()

        # Add connection record
        conn = Connection(
            from_element_type="line",
            from_element_id=line.id,
            from_terminal="1",
            to_element_type="bus",
            to_element_id=from_bus.id,
            to_terminal="term",
            is_active=True,
            metadata_json={"approved_by": approver_name, "candidate_id": candidate.candidate_id},
            source=f"OperatorApproval:{approver_name}",
            provenance="estimated",
        )
        db_session.add(conn)

        # Log diff in TopologyDiff if an authoritative version exists
        auth_version = db_session.query(TopologyVersion).filter_by(is_authoritative=True).first()
        if auth_version:
            diff = TopologyDiff(
                topology_version_id=auth_version.id,
                entity_type="line",
                entity_id=line.id,
                action="add",
                diff_payload={
                    "candidate_id": candidate.candidate_id,
                    "approved_by": approver_name,
                    "from_bus": from_bus.code,
                    "to_bus": to_bus.code,
                    "distance_meters": candidate.distance_meters,
                },
            )
            db_session.add(diff)

        db_session.flush()
        return line
